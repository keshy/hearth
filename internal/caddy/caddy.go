// Package caddy renders the full Caddyfile from the deployed apps and pushes
// it to Caddy's admin API. The file on disk is also what Caddy loads at boot.
package caddy

import (
	"bytes"
	"fmt"
	"io"
	"net/http"
	"os"
	"strings"
	"time"

	"appshome/internal/config"
	"appshome/internal/registry"
)

// AppHeader tells appshome which app a /_api request came from. Caddy sets
// it on app hosts and strips it everywhere else, so clients can't forge it.
const AppHeader = "X-Apps-Home-App"

// GeneratedCSP confines builder-made apps to their own origin: no external
// scripts, styles, fonts, frames or network calls, and no inline script.
const GeneratedCSP = "default-src 'self'; script-src 'self'; style-src 'self' 'unsafe-inline'; " +
	"img-src 'self' data: blob:; font-src 'self' data:; connect-src 'self'; media-src 'self' blob:; " +
	"object-src 'none'; frame-src 'none'; frame-ancestors 'none'; base-uri 'none'; form-action 'self'"

type Input struct {
	Cfg       config.Config
	Apps      []registry.App
	LiveDir   func(name string) string
	AdminHash string // bcrypt hash; private apps are unreachable without it
}

func Render(in Input) string {
	cfg := in.Cfg
	var b strings.Builder
	d := cfg.Domain

	fmt.Fprintf(&b, "# Generated by appshome. Manual edits are overwritten.\n")
	fmt.Fprintf(&b, "{\n\tadmin %s\n\thttp_port %d\n\thttps_port %d\n\tlocal_certs\n\tskip_install_trust\n\tstorage file_system %s\n}\n\n",
		cfg.CaddyAdmin, cfg.HTTPPort, cfg.HTTPSPort, quote(cfg.CaddyStorageDir()))

	fmt.Fprintf(&b, "%s, %s {\n\treverse_proxy %s {\n\t\theader_up -%s\n\t}\n}\n\n", d, cfg.AdminHost(), cfg.AppListen, AppHeader)

	// The trust page must work over plain HTTP, before the device trusts the CA.
	fmt.Fprintf(&b, "http://%s {\n\t@plain path /trust /trust/* /static/*\n\thandle @plain {\n\t\treverse_proxy %s {\n\t\t\theader_up -%s\n\t\t}\n\t}\n\thandle {\n\t\tredir https://{host}%s{uri}\n\t}\n}\n\n",
		d, cfg.AppListen, AppHeader, cfg.HTTPSSuffix())

	for _, a := range in.Apps {
		if a.Kind == registry.KindLink {
			fmt.Fprintf(&b, "%s {\n\tredir %s\n}\n\n", cfg.AppHost(a.Name), quote(a.URL))
			continue
		}
		fmt.Fprintf(&b, "%s {\n", cfg.AppHost(a.Name))
		if a.Private {
			if in.AdminHash == "" {
				b.WriteString("\trespond \"Set an admin password to open private apps.\" 503\n}\n\n")
				continue
			}
			fmt.Fprintf(&b, "\tbasic_auth {\n\t\tadmin %s\n\t}\n", in.AdminHash)
		}
		if a.Generated {
			fmt.Fprintf(&b, "\theader Content-Security-Policy %s\n", quote(GeneratedCSP))
		}
		switch a.Kind {
		case registry.KindStatic:
			writePlatformAPI(&b, cfg, a)
			b.WriteString("\thandle {\n")
			writeStatic(&b, "\t\t", in.LiveDir(a.Name))
			b.WriteString("\t}\n")
		case registry.KindHybrid:
			writePlatformAPI(&b, cfg, a)
			fmt.Fprintf(&b, "\t@api path %s %s/*\n\thandle @api {\n", a.APIPrefix, a.APIPrefix)
			writeProxy(&b, "\t\t", a)
			b.WriteString("\t}\n\thandle {\n")
			writeStatic(&b, "\t\t", in.LiveDir(a.Name))
			b.WriteString("\t}\n")
		case registry.KindProxied:
			writeProxy(&b, "\t", a)
		}
		b.WriteString("}\n\n")
	}

	labels := strings.Count(d, ".") + 1
	fmt.Fprintf(&b, "*.%s {\n\tredir %s/?missing={labels.%d} 302\n}\n", d, cfg.PortalURL(), labels)
	return b.String()
}

// writePlatformAPI routes /_api/* (shared data, builder) to appshome, tagged
// with the calling app's name.
func writePlatformAPI(b *strings.Builder, cfg config.Config, a registry.App) {
	fmt.Fprintf(b, "\thandle /_api/* {\n\t\treverse_proxy %s {\n\t\t\theader_up %s %s\n\t\t}\n\t}\n", cfg.AppListen, AppHeader, a.Name)
}

func writeStatic(b *strings.Builder, in, dir string) {
	fmt.Fprintf(b, "%sencode zstd gzip\n%sroot * %s\n%stry_files {path} {path}/index.html /index.html\n%sfile_server\n",
		in, in, quote(dir), in, in)
}

func writeProxy(b *strings.Builder, in string, a registry.App) {
	if strings.HasPrefix(a.Upstream, "https://") && a.UpstreamInsecure {
		fmt.Fprintf(b, "%sreverse_proxy %s {\n%s\ttransport http {\n%s\t\ttls_insecure_skip_verify\n%s\t}\n%s}\n",
			in, a.Upstream, in, in, in, in)
		return
	}
	fmt.Fprintf(b, "%sreverse_proxy %s\n", in, a.Upstream)
}

func quote(s string) string {
	return `"` + strings.NewReplacer(`\`, `\\`, `"`, `\"`).Replace(s) + `"`
}

// Write renders the Caddyfile to disk without touching the running Caddy.
// It is 0600 because it contains the admin password hash.
func Write(in Input) ([]byte, error) {
	body := []byte(Render(in))
	if err := os.MkdirAll(in.Cfg.DataDir, 0o755); err != nil {
		return nil, err
	}
	return body, config.WriteFileAtomic(in.Cfg.CaddyfilePath(), body, 0o600)
}

// Sync writes the Caddyfile and asks Caddy to load it.
func Sync(in Input) error {
	body, err := Write(in)
	if err != nil {
		return err
	}
	return Load(in.Cfg.CaddyAdmin, body)
}

var client = &http.Client{Timeout: 20 * time.Second}

func Load(adminAddr string, caddyfile []byte) error {
	req, err := http.NewRequest(http.MethodPost, "http://"+adminAddr+"/load", bytes.NewReader(caddyfile))
	if err != nil {
		return err
	}
	req.Header.Set("Content-Type", "text/caddyfile")
	resp, err := client.Do(req)
	if err != nil {
		return fmt.Errorf("caddy admin API unreachable at %s: %w", adminAddr, err)
	}
	defer resp.Body.Close()
	if resp.StatusCode/100 != 2 {
		msg, _ := io.ReadAll(io.LimitReader(resp.Body, 4096))
		return fmt.Errorf("caddy rejected config (%s): %s", resp.Status, strings.TrimSpace(string(msg)))
	}
	return nil
}
